PRI=['SH','TR','BI','FA','GL','HM','QD','CF','CH','CR','BK']  # приоритет при перекрытии (раньше = главнее)
def raw(g):
    m=Image.new('L',(W,H),0);d=ImageDraw.Draw(m)
    for p in G[g]: d.polygon(p,fill=255)
    return np.asarray(m)>0
def masks():
    taken=np.zeros((H,W),bool);M={}
    for g in PRI:
        r=raw(g)&~taken;M[g]=r;taken|=r
    return M
